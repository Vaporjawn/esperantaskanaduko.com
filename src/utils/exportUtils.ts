/**
 * Utility functions for exporting data in various formats
 */

import type { TranslationHistoryEntry } from '@/types/history';

/**
 * Download data as a file
 */
export function downloadFile(content: string, filename: string, mimeType: string): void {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

/**
 * Export history as JSON
 */
export function exportHistoryAsJSON(history: TranslationHistoryEntry[]): void {
  const jsonContent = JSON.stringify(history, null, 2);
  const timestamp = new Date().toISOString().split('T')[0];
  downloadFile(
    jsonContent,
    `esperanto-translation-history-${timestamp}.json`,
    'application/json'
  );
}

/**
 * Export history as CSV
 */
export function exportHistoryAsCSV(history: TranslationHistoryEntry[]): void {
  const headers = [
    'ID',
    'Date',
    'Type',
    'Original Text',
    'Translated Text',
    'Source Language',
    'Target Language',
    'Character Count',
    'URL',
    'Page Title'
  ];

  const rows = history.map(entry => [
    entry.id,
    new Date(entry.timestamp).toLocaleString(),
    entry.translationType,
    `"${entry.originalText.replace(/"/g, '""')}"`, // Escape quotes
    `"${entry.translatedText.replace(/"/g, '""')}"`,
    entry.sourceLang,
    entry.targetLang,
    entry.charCount.toString(),
    entry.url || '',
    entry.pageTitle ? `"${entry.pageTitle.replace(/"/g, '""')}"` : ''
  ]);

  const csvContent = [
    headers.join(','),
    ...rows.map(row => row.join(','))
  ].join('\n');

  const timestamp = new Date().toISOString().split('T')[0];
  downloadFile(
    csvContent,
    `esperanto-translation-history-${timestamp}.csv`,
    'text/csv'
  );
}

